"""GLM engine prompt templates: three-phase pipeline.

Phase 1: text-only audit with rules + negative cases
Phase 2: Qwen-VL page screenshot analysis (guided by Phase 1 page refs)
Phase 3: final GLM synthesis combining text + image results

These prompts encode the 5-category red-line taxonomy and the
甲方/乙方 differentiation logic — they are the GLM engine's soul.
"""

import re


def phase1_prompt(ent_name: str, rules: str, negative_cases: str,
                  findings_text: str, full_text: str) -> str:
    """Phase 1: GLM text-only audit prompt."""
    ent_type = '乙方' if '乙方' in ent_name else '甲方'
    type_note = (
        "注意：甲方企业的数据战略必须反映企业自身行业特征，"
        "出现其他行业关键词视为模板张冠李戴。"
        if ent_type == "甲方"
        else "注意：乙方企业材料中包含不同客户的行业关键词是正常的，"
             "重点审查合同纯度和实证多样性。"
    )

    return f"""你是一名资深 DCMM 审计专家。请基于以下【审计准则】对企业 <{ent_name}> 的报告进行深度审计。

该企业为【{ent_type}】。
{type_note}

### 【审计准则】
{rules}

### 【负面案例参考】
{negative_cases}

### 【系统自动检测到的跨文件矛盾】
{findings_text}

### 【企业报告全文内容】
{full_text}

### 【任务要求】

**核心原则：宁可漏判，不可错杀。但真正的张冠李戴必须抓住。**
1. 一票否决红线仅包括以下5类：
   (a) **严重张冠李戴**：甲方报告任一已提交治理文档（数据战略/治理/架构/质量/安全/标准/生存周期/提升建议）正文或打分表中，出现与企业自身行业明显矛盾的其他行业特征关键词（如制造企业出现"门诊""病历"、船舶设计院出现"软件和信息技术服务行业""互动直播部"），即判一票否决，不要求系统性多处出现。排除合理引用：出现在"学习了""借鉴""对标""参考了""研究了""标杆企业""跨行业""等企业"等表述中、作为跨行业案例或集团交叉引用提及的，不算张冠李戴。
   甲方报告任一已提交治理文档正文或打分表中，以制度/办法/规范的主语或文件命名出现其他企业名称（非简称变体、非评估机构、非其自身客户），即判一票否决，不要求多处印证。如：制度正文写"广州方维信息技术有限公司《数据质量需求管理办法》旨在…"、提升建议写"建议长春嘉诚进一步…"、数据仓库规范命名为"OPPEIN-BI"。
   **乙方特殊规则**：乙方企业材料中出现客户名称、客户红头文件、客户制度文档是正常的——这说明乙方为客户提供了数据治理服务。只有当乙方自己的内部治理文档（非项目交付物）抄袭了其他公司，才算张冠李戴。
   (b) 数据战略/制度严重错误：通篇抽象通用且无截图、文控制度充当数据管理办法、命名混乱。
   (c) 数据质量域无任何系统截图：检查每页图片标注[本页含N张图片]，有图片则不能判"完全缺失"。
   (d) 数据架构域明显Demo/网图：含占位符、测试数据、水印。
   (e) 乙方合同纯度不足：无任何数据管理类合同，需至少两个不同客户。

2. **以下不属于一票否决，而是红线质疑**：红头文件/发文缺失、年限不足、物理表冒充逻辑模型、跨域证据不足。

3. 提取具体的证据页码（如 Pxx，使用文件内物理页码）。发现的所有问题必须标注：文件名、页码、原文片段。

4. **红头文件审查规则**：文本中出现"红头""发布""发文""管理办法"等关键词且页面有图片，必须标注页码供视觉验证，不能仅因文字未见"公章"就判缺失。

请直接输出审计报告内容。"""


def phase2_vl_prompt(ent_name: str) -> str:
    """Phase 2: Qwen-VL page screenshot analysis prompt."""
    _ent_short = re.sub(r'^\d+、', '', ent_name)
    _ent_short = re.sub(r'[+\-]?[345]级[+\-]?[甲乙]方?', '', _ent_short)
    _ent_short = re.sub(
        r'(股份有限公司|有限公司|有限责任公司|集团|股份|有限)', '', _ent_short
    ).strip()
    _ent_core = _ent_short[:6] if len(_ent_short) >= 4 else _ent_short

    return (
        f'这是「{ent_name}」的DCMM评估报告中的一页。该企业简称可能为"{_ent_core}"或包含"{_ent_core}"字样。'
        '请先判断页面主体内容类型：A)系统截图 B)制度/文档扫描件(含红头文件) C)流程图/架构图 D)表格/文字。'
        '然后：1)简要描述内容 2)仅当为系统截图(A类)时判断是否像真实运行的系统（有真实数据/企业名称）还是产品demo。'
        f'注意：截图中如果出现"{_ent_core}"或其变体（含简称、股票名称等），应识别为真实企业标识，不是虚构公司名。'
        '3)如果不是系统截图，请明确说明"非系统截图"并指出实际类型。'
        '4)特别检测：该页是否包含红头文件（带公章/发文文号/发文日期的正式发文页）或制度发布记录。'
        '如果是，明确说明"发现红头文件"并描述公章/文号/日期等关键信息。限200字。'
    )


def phase3_prompt(ent_name: str, rules: str, findings_text: str,
                    image_text: str, phase1_truncated: str) -> str:
    """Phase 3: GLM final synthesis combining text + image results."""
    ent_type = '乙方' if '乙方' in ent_name else '甲方'

    return f"""你是一名资深 DCMM 审计专家。请基于以下所有信息对企业 <{ent_name}> 进行最终审计判定。

该企业为【{ent_type}】。

### 【审计准则】
{rules}

### 【阶段一文本审计初步结论】
{phase1_truncated}

### 【系统自动检测到的跨文件矛盾】
{findings_text}

### 【阶段二系统截图视觉分析结果（Qwen-VL-Max）】
{image_text if image_text else '未进行视觉分析'}

### 【任务要求】

**核心原则：宁可漏判，不可错杀。但真正的张冠李戴必须抓住。**

一票否决仅限以下5类：

(a) **严重张冠李戴**：甲方报告任一已提交治理文档（数据战略/治理/架构/质量/安全/标准/生存周期/提升建议）正文或打分表中，出现与企业自身行业**明显矛盾**的其他行业特征关键词（如制造企业出现"门诊""病历"、船舶设计院出现"软件和信息技术服务行业""互动直播部"），即判一票否决，不要求系统性多处出现。
    - 判断标准：该关键词是否出现在"学习了""借鉴""对标""参考了""研究了""标杆企业""跨行业""等企业"等合理引用表述中。如：卫浴企业的战略目标写成"成为电源领域技术标杆"——这是明显的模板套用，不是跨行业参考。
    - 集团下属企业提到集团内其他业务的术语（如炼化企业提到"油气井"），属于正常的集团内交叉引用，不算张冠李戴。
    - 甲方报告任一已提交治理文档正文或打分表中，以制度/办法/规范的主语或文件命名出现其他企业名称（非简称变体、非评估机构、非其自身客户），即判一票否决，不要求多处印证。如：制度正文写"广州方维信息技术有限公司《数据质量需求管理办法》旨在…"、提升建议写"建议长春嘉诚进一步…"、数据仓库规范命名为"OPPEIN-BI"。
    - **乙方特殊规则**：乙方材料中出现客户名称、客户红头文件、客户制度文档是正常的——这说明乙方为客户提供了数据治理服务。只有当乙方自己的内部治理文档（非项目交付物）抄袭了其他公司，才算张冠李戴。

(b) **数据战略/制度严重错误**：通篇抽象通用且无截图、文控制度充当数据管理办法（真正替代而非偶尔提到）、命名混乱。

(c) **数据质量域无任何系统截图**：检查每页图片标注[本页含N张图片]，有图片则不能判"完全缺失"。

(d) **数据架构域明显Demo/网图**：含占位符、测试数据、水印。截图"不够充分"≠"明显Demo"。

(e) **乙方合同纯度不足**：无任何数据管理类合同，需至少两个不同客户。

**以下不属于一票否决，而是红线质疑**：红头文件/发文缺失、年限不足、物理表冒充逻辑模型、跨域证据不足。

**红头文件穿透规则**：文本中出现"红头""发布""发文""管理办法"等关键词且页面有图片，必须标注页码供视觉验证。

### 输出格式要求

1. **不要写开头套话**。直接从结论开始。
2. 报告结构：

**审计结论**：[踩红线（一票否决）/红线质疑/一般性问题/无]
**最终结论**：[不通过/复审/修改/通过]
**判定依据**：一句话说明为什么得出这个结论。

---
（以下仅列出有问题的项，没有问题的不要写，不要解释审计过程）

**踩红线**（如有）：
- 问题1：[问题名称]
  - 证据：[文件名 P页码] 原文："引号内放原文片段"
  - 解读：[为什么这是犯规的，1-2句话]

**红线质疑**（如有）：
- 问题1：[问题名称]
  - 证据：[文件名 P页码] 原文："引号内放原文片段"
  - 解读：[为什么存疑，1-2句话]

**一般性问题**（如有）：
- 问题1：[问题名称]
  - 证据：[文件名 P页码]
  - 解读：[1句话]

3. 不要写"整改要求""后续建议""现场核验要求"等。
4. 不要解释"阶段一""阶段二""视觉分析确认"等审计过程。
5. 证据必须包含：文件名、页码、原文片段（用引号标注）。
6. 如果某个质疑点经过验证后结论是"没问题"，就不要写出来。

请直接输出最终审计报告。"""
